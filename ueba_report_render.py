#!/usr/bin/env python3
"""
Report renderers — PDF, Excel, CSV, HTML, JSON and XML (RFP 34, 39, 62).

Every renderer consumes the same document produced by ueba_reports.build_report
and knows nothing about UEBA. Adding a format means adding one function here and
one entry in RENDERERS.

PDF uses reportlab and Excel uses openpyxl. Both are optional imports: if a site
has not installed them the other four formats still work and the caller gets a
clear error naming the missing package, rather than the dashboard failing to
start.
"""
import csv
import io
import json
from datetime import datetime
from xml.sax.saxutils import escape as _xesc

# ── Palette ─────────────────────────────────────────────────────────────────
# Reports are printed and emailed, so this is a LIGHT theme regardless of what
# the dashboard is set to. Ink on white survives a photocopier; the dashboard's
# dark theme does not.
INK       = "#101820"
MUTED     = "#5b6b7a"
RULE      = "#d7dee5"
ACCENT    = "#0b6fa4"
BAR       = "#2e86c1"
BAND      = "#f2f6f9"
SEVERE    = "#b3261e"


def _fmt_generated(iso):
    try:
        d = datetime.fromisoformat(str(iso).replace("Z", "+00:00"))
        return d.strftime("%d %b %Y, %H:%M UTC")
    except (ValueError, TypeError):
        return str(iso or "")


def _rows_of(sec):
    """Every section kind projected to (columns, rows) for the flat formats."""
    k = sec.get("kind")
    if k == "table":
        return sec.get("columns") or [], [[("" if c is None else str(c)) for c in r]
                                          for r in sec.get("rows") or []]
    if k == "metrics":
        return ["Metric", "Value", "Note"], [
            [i.get("label", ""), str(i.get("value", "")), i.get("note", "") or ""]
            for i in sec.get("items") or []]
    if k == "bars":
        return ["Label", "Value"], [[i.get("label", ""), str(i.get("value", ""))]
                                    for i in sec.get("items") or []]
    if k == "text":
        return ["Text"], [[line] for line in str(sec.get("body", "")).splitlines()]
    return [], []


# ── JSON ────────────────────────────────────────────────────────────────────

def render_json(rep):
    return json.dumps(rep, indent=2, ensure_ascii=False).encode("utf-8")


# ── XML ─────────────────────────────────────────────────────────────────────

def render_xml(rep):
    out = ['<?xml version="1.0" encoding="UTF-8"?>']
    w = rep.get("window") or {}
    out.append(
        f'<ueba_report id="{_xesc(str(rep.get("report_id", "")))}" '
        f'generated_at="{_xesc(str(rep.get("generated_at", "")))}" '
        f'window_hours="{_xesc(str(w.get("hours", "")))}">'
    )
    out.append(f'  <title>{_xesc(str(rep.get("title", "")))}</title>')
    out.append(f'  <subtitle>{_xesc(str(rep.get("subtitle", "")))}</subtitle>')
    for sec in rep.get("sections") or []:
        cols, rows = _rows_of(sec)
        out.append(f'  <section kind="{_xesc(str(sec.get("kind", "")))}" '
                   f'title="{_xesc(str(sec.get("title", "")))}">')
        if sec.get("note"):
            out.append(f'    <note>{_xesc(str(sec["note"]))}</note>')
        for r in rows:
            out.append("    <row>")
            for c, v in zip(cols, r):
                tag = _tagify(c)
                out.append(f"      <{tag}>{_xesc(str(v))}</{tag}>")
            out.append("    </row>")
        out.append("  </section>")
    out.append("</ueba_report>")
    return ("\n".join(out) + "\n").encode("utf-8")


def _tagify(name):
    """Column heading -> a legal XML element name."""
    s = "".join(ch if (ch.isalnum() or ch in "._-") else "_" for ch in str(name).strip())
    s = s.lstrip("._-0123456789") or "field"
    return s.lower()


# ── CSV ─────────────────────────────────────────────────────────────────────

def render_csv(rep):
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow([rep.get("title", "UEBA Report")])
    w.writerow(["Generated", _fmt_generated(rep.get("generated_at"))])
    w.writerow(["Period", (rep.get("window") or {}).get("label", "")])
    if rep.get("generated_by"):
        w.writerow(["Generated by", rep["generated_by"]])
    w.writerow([])
    # One CSV cannot be several tables, so sections are stacked with their own
    # heading rows. Analysts open these in Excel and read them top to bottom.
    for sec in rep.get("sections") or []:
        cols, rows = _rows_of(sec)
        w.writerow([f"== {sec.get('title', '')} =="])
        if sec.get("note"):
            w.writerow([sec["note"]])
        if cols:
            w.writerow(cols)
        for r in rows:
            w.writerow(r)
        w.writerow([])
    return buf.getvalue().encode("utf-8-sig")   # BOM so Excel reads UTF-8


# ── HTML ────────────────────────────────────────────────────────────────────

def _h(s):
    return (str("" if s is None else s).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


def render_html(rep):
    w = rep.get("window") or {}
    parts = [
        "<!doctype html><html><head><meta charset='utf-8'>",
        f"<title>{_h(rep.get('title'))}</title>",
        "<style>",
        f"body{{font:14px/1.5 -apple-system,Segoe UI,Roboto,sans-serif;color:{INK};"
        "max-width:1000px;margin:32px auto;padding:0 20px;background:#fff}",
        f"h1{{font-size:24px;margin:0 0 4px}}h2{{font-size:17px;margin:30px 0 8px;"
        f"padding-bottom:6px;border-bottom:2px solid {RULE};color:{ACCENT}}}",
        f".sub{{color:{MUTED};margin:0 0 18px}}",
        f"table{{border-collapse:collapse;width:100%;margin:8px 0;font-size:13px}}",
        f"th{{text-align:left;background:{BAND};padding:7px 9px;border-bottom:1px solid {RULE}}}",
        f"td{{padding:6px 9px;border-bottom:1px solid #eef2f5;vertical-align:top}}",
        f".note{{color:{MUTED};font-size:12.5px;margin:4px 0 10px}}",
        ".m{display:flex;flex-wrap:wrap;gap:10px;margin:10px 0}",
        f".m div{{border:1px solid {RULE};border-radius:6px;padding:9px 13px;min-width:150px}}",
        f".m b{{display:block;font-size:20px;color:{ACCENT}}}",
        f".m span{{color:{MUTED};font-size:12px}}",
        f".bar{{height:14px;background:{BAR};border-radius:2px}}",
        "pre{white-space:pre-wrap;font:inherit;margin:6px 0}",
        f"footer{{margin-top:40px;color:{MUTED};font-size:12px;border-top:1px solid {RULE};"
        "padding-top:10px}",
        "</style></head><body>",
        f"<h1>{_h(rep.get('title'))}</h1>",
        f"<p class='sub'>{_h(rep.get('subtitle'))}<br>"
        f"{_h(rep.get('site'))} &middot; {_h(w.get('label'))} &middot; "
        f"generated {_h(_fmt_generated(rep.get('generated_at')))}"
        + (f" by {_h(rep.get('generated_by'))}" if rep.get("generated_by") else "")
        + "</p>",
    ]
    for sec in rep.get("sections") or []:
        parts.append(f"<h2>{_h(sec.get('title'))}</h2>")
        if sec.get("note"):
            parts.append(f"<p class='note'>{_h(sec['note'])}</p>")
        kind = sec.get("kind")
        if kind == "text":
            parts.append(f"<pre>{_h(sec.get('body'))}</pre>")
        elif kind == "metrics":
            parts.append("<div class='m'>")
            for i in sec.get("items") or []:
                parts.append(f"<div><b>{_h(i.get('value'))}</b>{_h(i.get('label'))}"
                             + (f"<span><br>{_h(i['note'])}</span>" if i.get("note") else "")
                             + "</div>")
            parts.append("</div>")
        elif kind == "bars":
            items = sec.get("items") or []
            mx = max([float(i.get("value") or 0) for i in items] or [1]) or 1
            parts.append("<table>")
            for i in items:
                v = float(i.get("value") or 0)
                parts.append(
                    f"<tr><td style='width:34%'>{_h(i.get('label'))}</td>"
                    f"<td style='width:52%'><div class='bar' style='width:{max(1, v / mx * 100):.1f}%'></div></td>"
                    f"<td style='text-align:right'>{_h(f'{int(v):,}')}</td></tr>")
            parts.append("</table>")
        else:
            cols, rows = _rows_of(sec)
            parts.append("<table><thead><tr>"
                         + "".join(f"<th>{_h(c)}</th>" for c in cols)
                         + "</tr></thead><tbody>")
            for r in rows:
                parts.append("<tr>" + "".join(f"<td>{_h(c)}</td>" for c in r) + "</tr>")
            parts.append("</tbody></table>")
    parts.append(f"<footer>{_h(rep.get('site'))} — generated automatically. "
                 "Figures exclude alerts suppressed as false positives.</footer>")
    parts.append("</body></html>")
    return "\n".join(parts).encode("utf-8")


# ── Excel ───────────────────────────────────────────────────────────────────

def render_xlsx(rep):
    try:
        from openpyxl import Workbook
        from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
        from openpyxl.utils import get_column_letter
    except ImportError as e:
        raise RuntimeError("Excel export needs the 'openpyxl' package: "
                           "pip install openpyxl") from e

    wb = Workbook()
    ws = wb.active
    ws.title = "Overview"
    head = Font(bold=True, color="FFFFFF")
    fill = PatternFill("solid", fgColor=ACCENT.lstrip("#"))
    thin = Side(style="thin", color=RULE.lstrip("#"))
    border = Border(bottom=thin)

    ws.append([rep.get("title", "UEBA Report")])
    ws["A1"].font = Font(bold=True, size=15)
    ws.append([rep.get("subtitle", "")])
    ws.append(["Period", (rep.get("window") or {}).get("label", "")])
    ws.append(["Generated", _fmt_generated(rep.get("generated_at"))])
    if rep.get("generated_by"):
        ws.append(["Generated by", rep["generated_by"]])
    ws.append([])
    ws.append(["Section", "Rows"])
    for c in ws[ws.max_row]:
        c.font, c.fill = head, fill

    used = set()
    for sec in rep.get("sections") or []:
        cols, rows = _rows_of(sec)
        title = sec.get("title") or "Section"
        # Excel sheet names: <=31 chars, no []:*?/\, and must be unique.
        name = "".join(ch for ch in title if ch not in "[]:*?/\\")[:28] or "Section"
        base, i = name, 2
        while name.lower() in used:
            name = f"{base[:26]}_{i}"
            i += 1
        used.add(name.lower())
        ws.append([title, len(rows)])

        sh = wb.create_sheet(name)
        if sec.get("note"):
            sh.append([sec["note"]])
            sh.append([])
        if cols:
            sh.append(cols)
            for c in sh[sh.max_row]:
                c.font, c.fill, c.border = head, fill, border
        for r in rows:
            sh.append([_num(v) for v in r])
        # Width from content, clamped so one long signature cannot make a
        # 300-character column that nobody can read.
        for ci, col in enumerate(cols or ["Value"], start=1):
            longest = max([len(str(col))] +
                          [len(str(r[ci - 1])) for r in rows if len(r) >= ci][:200] or [10])
            sh.column_dimensions[get_column_letter(ci)].width = min(max(longest + 2, 10), 48)
        sh.freeze_panes = sh.cell(row=(3 if sec.get("note") else 1) + 1, column=1)
        for c in (sh[1] if sh.max_row else []):
            c.alignment = Alignment(vertical="top", wrap_text=True)

    ws.column_dimensions["A"].width = 44
    ws.column_dimensions["B"].width = 14
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def _num(v):
    """Write numbers as numbers so Excel can chart and total them."""
    s = str(v)
    t = s.replace(",", "")
    if t and (t.replace(".", "", 1).replace("-", "", 1).isdigit()):
        try:
            return int(t) if "." not in t else float(t)
        except ValueError:
            return s
    return s


# ── PDF ─────────────────────────────────────────────────────────────────────

def render_pdf(rep):
    try:
        from reportlab.lib import colors
        from reportlab.lib.enums import TA_LEFT
        from reportlab.lib.pagesizes import A4, landscape
        from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
        from reportlab.lib.units import mm
        from reportlab.graphics.shapes import Drawing, Rect
        from reportlab.platypus import (BaseDocTemplate, Frame, KeepTogether,
                                        PageTemplate, Paragraph, Spacer, Table,
                                        TableStyle)
    except ImportError as e:
        raise RuntimeError("PDF export needs the 'reportlab' package: "
                           "pip install reportlab") from e

    # Landscape: the widest tables here are six columns of alert detail, and in
    # portrait they wrap into unreadable slivers.
    page = landscape(A4)
    W, H = page
    ML = MR = 14 * mm
    avail = W - ML - MR

    ss = getSampleStyleSheet()
    body = ParagraphStyle("b", parent=ss["Normal"], fontName="Helvetica",
                          fontSize=8.4, leading=11, textColor=colors.HexColor(INK))
    cell = ParagraphStyle("c", parent=body, fontSize=8, leading=10)
    cellb = ParagraphStyle("cb", parent=cell, fontName="Helvetica-Bold")
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], fontName="Helvetica-Bold",
                        fontSize=12.5, leading=15, spaceBefore=12, spaceAfter=4,
                        textColor=colors.HexColor(ACCENT))
    note = ParagraphStyle("n", parent=body, fontSize=8, leading=10.5,
                          textColor=colors.HexColor(MUTED), spaceAfter=4)
    big = ParagraphStyle("big", parent=body, fontSize=15, leading=18,
                         fontName="Helvetica-Bold", textColor=colors.HexColor(ACCENT))
    lbl = ParagraphStyle("lbl", parent=body, fontSize=7.6, leading=9.5,
                         textColor=colors.HexColor(MUTED))

    meta = {
        "title": rep.get("title", "UEBA Report"),
        "site":  rep.get("site", ""),
        "when":  _fmt_generated(rep.get("generated_at")),
        "win":   (rep.get("window") or {}).get("label", ""),
    }

    def decorate(canv, doc):
        canv.saveState()
        canv.setFont("Helvetica-Bold", 8.5)
        canv.setFillColor(colors.HexColor(ACCENT))
        canv.drawString(ML, H - 9 * mm, meta["title"])
        canv.setFont("Helvetica", 7.6)
        canv.setFillColor(colors.HexColor(MUTED))
        canv.drawRightString(W - MR, H - 9 * mm, f'{meta["site"]}  |  {meta["win"]}')
        canv.setStrokeColor(colors.HexColor(RULE))
        canv.setLineWidth(0.6)
        canv.line(ML, H - 11 * mm, W - MR, H - 11 * mm)
        canv.line(ML, 12 * mm, W - MR, 12 * mm)
        canv.setFont("Helvetica", 7.4)
        canv.drawString(ML, 8.5 * mm, f'Generated {meta["when"]}')
        canv.drawRightString(W - MR, 8.5 * mm, f"Page {canv.getPageNumber()}")
        canv.restoreState()

    buf = io.BytesIO()
    doc = BaseDocTemplate(buf, pagesize=page, leftMargin=ML, rightMargin=MR,
                          topMargin=16 * mm, bottomMargin=16 * mm,
                          title=meta["title"], author=meta["site"])
    doc.addPageTemplates([PageTemplate(
        id="main",
        frames=[Frame(ML, 15 * mm, avail, H - 31 * mm, id="f", showBoundary=0)],
        onPage=decorate)])

    story = [Paragraph(meta["title"], ParagraphStyle(
        "t", parent=ss["Title"], fontName="Helvetica-Bold", fontSize=19,
        leading=23, alignment=TA_LEFT, textColor=colors.HexColor(INK), spaceAfter=2))]
    if rep.get("subtitle"):
        story.append(Paragraph(rep["subtitle"], note))
    byline = f'{meta["site"]} &middot; {meta["win"]} &middot; generated {meta["when"]}'
    if rep.get("generated_by"):
        byline += f' by {_h(rep["generated_by"])}'
    story.append(Paragraph(byline, note))
    story.append(Spacer(1, 4))

    for sec in rep.get("sections") or []:
        flow = [Paragraph(_h(sec.get("title", "")), h2)]
        if sec.get("note"):
            flow.append(Paragraph(_h(sec["note"]), note))
        kind = sec.get("kind")

        if kind == "text":
            for line in str(sec.get("body", "")).splitlines():
                flow.append(Paragraph(_h(line) or "&nbsp;", body))

        elif kind == "metrics":
            items = sec.get("items") or []
            cells = []
            for i in items:
                stack = [Paragraph(_h(i.get("value")), big),
                         Paragraph(_h(i.get("label")), lbl)]
                if i.get("note"):
                    stack.append(Paragraph(_h(i["note"]), lbl))
                cells.append(stack)
            per = 4
            for r0 in range(0, len(cells), per):
                chunk = cells[r0:r0 + per]
                chunk += [[Paragraph("", lbl)]] * (per - len(chunk))
                t = Table([chunk], colWidths=[avail / per] * per)
                t.setStyle(TableStyle([
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("LEFTPADDING", (0, 0), (-1, -1), 7),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 7),
                    ("TOPPADDING", (0, 0), (-1, -1), 6),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                    ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor(RULE)),
                    ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor(RULE)),
                ]))
                flow.append(t)
                flow.append(Spacer(1, 4))

        elif kind == "bars":
            items = sec.get("items") or []
            mx = max([float(i.get("value") or 0) for i in items] or [1]) or 1
            barcol = avail * 0.52
            rows = []
            for i in items:
                v = float(i.get("value") or 0)
                # Each bar is an explicitly drawn rectangle. An earlier version
                # shaded a table cell and masked the remainder with a white
                # rule, which silently produced identical-length bars for every
                # value — a chart that looks plausible and says nothing.
                frac = min(1.0, max(0.006, v / mx))
                d = Drawing(barcol, 9)
                d.add(Rect(0, 0, barcol * frac, 9,
                           fillColor=colors.HexColor(BAR), strokeColor=None))
                rows.append([Paragraph(_h(i.get("label")), cell), d,
                             Paragraph(f"{v:,.0f}", cell)])
            t = Table(rows, colWidths=[avail * 0.30, barcol, avail * 0.18])
            t.setStyle(TableStyle([
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("ALIGN", (2, 0), (2, -1), "RIGHT"),
                ("LINEBELOW", (0, 0), (-1, -2), 0.4, colors.HexColor("#eef2f5")),
                ("TOPPADDING", (0, 0), (-1, -1), 2.5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
                ("LEFTPADDING", (1, 0), (1, -1), 0),
                ("RIGHTPADDING", (1, 0), (1, -1), 6),
            ]))
            flow.append(t)

        else:
            cols, rows = _rows_of(sec)
            if rows:
                widths = _col_widths(cols, rows, avail)
                data = [[Paragraph(_h(c), cellb) for c in cols]]
                for r in rows:
                    data.append([Paragraph(_h(c), cell) for c in r])
                t = Table(data, colWidths=widths, repeatRows=1)
                st = [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor(ACCENT)),
                    ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor(RULE)),
                    ("TOPPADDING", (0, 0), (-1, -1), 3.5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 3.5),
                    ("LEFTPADDING", (0, 0), (-1, -1), 4),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                ]
                for n in range(1, len(data)):
                    if n % 2 == 0:
                        st.append(("BACKGROUND", (0, n), (-1, n), colors.HexColor(BAND)))
                t.setStyle(TableStyle(st))
                flow.append(t)

        # Keep a heading with at least the start of its content, but never wrap a
        # long table in KeepTogether or it cannot split across pages at all.
        story.append(KeepTogether(flow[:2]) if len(flow) > 2 else flow[0])
        story.extend(flow[2:] if len(flow) > 2 else flow[1:])
        story.append(Spacer(1, 5))

    doc.build(story)
    return buf.getvalue()


def _col_widths(cols, rows, avail):
    """Proportional widths from sampled content.

    Two rules beyond "wide content gets wide columns":

    * A column is never narrower than its heading's longest WORD. Without this,
      a many-column table squeezes short-named columns until "Score" renders as
      "Sc or e" down three lines — the table is technically complete and
      practically unreadable.
    * Typical content drives the width, not the worst case. Sizing on the single
      longest cell lets one 300-character signature claim half the page while
      every other column starves, so the 90th percentile is used instead.
    """
    n = len(cols)
    if not n:
        return None
    sample = rows[:250]

    # Helvetica-Bold 8pt averages a little over 5pt per character; headings are
    # bold, so sizing them with the regular-weight figure is what let "Score"
    # break into "Scor e".
    HEAD_CHAR_PT = 5.2
    PADDING_PT = 9.0

    floors, weights = [], []
    for i in range(n):
        lens = sorted(len(str(r[i])) for r in sample if len(r) > i)
        typical = lens[int(len(lens) * 0.9)] if lens else 8
        longest_word = max((len(w) for w in str(cols[i]).split()), default=4)
        floors.append(longest_word * HEAD_CHAR_PT + PADDING_PT)
        weights.append(min(max(typical, longest_word, 5), 40))

    # Floors first, then share what is left over in proportion to content. An
    # earlier version lifted columns to their floor and THEN renormalised to the
    # frame width, which scaled them straight back under it — the floors had no
    # effect at all. Allocating the remainder instead makes them binding, and
    # the total is exact by construction rather than by a correction pass.
    slack = avail - sum(floors)
    if slack <= 0:
        # More columns than the page can honour. Nothing fits properly, so fall
        # back to proportional and let it wrap rather than overflow the frame.
        scale = avail / sum(floors)
        return [f * scale for f in floors]

    wtotal = sum(weights) or 1
    return [floors[i] + slack * (weights[i] / wtotal) for i in range(n)]


# ── Registry ────────────────────────────────────────────────────────────────

RENDERERS = {
    "pdf":  (render_pdf,  "application/pdf",  "pdf"),
    "xlsx": (render_xlsx, "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", "xlsx"),
    "csv":  (render_csv,  "text/csv; charset=utf-8", "csv"),
    "html": (render_html, "text/html; charset=utf-8", "html"),
    "json": (render_json, "application/json", "json"),
    "xml":  (render_xml,  "application/xml; charset=utf-8", "xml"),
}


def render(rep, fmt):
    """(bytes, mimetype, extension) for `fmt`."""
    fmt = (fmt or "pdf").lower()
    if fmt == "excel":
        fmt = "xlsx"
    if fmt not in RENDERERS:
        raise ValueError(f"unknown format {fmt!r}; expected one of "
                         f"{sorted(RENDERERS)}")
    fn, mime, ext = RENDERERS[fmt]
    return fn(rep), mime, ext


def available_formats():
    """Formats this install can actually produce, so the UI never offers a
    button that will fail. PDF and Excel depend on optional packages."""
    out = []
    for fmt in RENDERERS:
        if fmt == "pdf":
            try:
                import reportlab  # noqa: F401
            except ImportError:
                continue
        if fmt == "xlsx":
            try:
                import openpyxl  # noqa: F401
            except ImportError:
                continue
        out.append(fmt)
    return out
